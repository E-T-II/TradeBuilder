export function translateIllustration(language: LanguageCode, source: string): string {
  if (language === "es" && Object.hasOwn(spanishLabels, source)) return spanishLabels[source];
  const index = messages.findIndex((message) => message === source);
  if (index !== -1) {
    const translation = oddsIllustrationTranslations[language][index];
    if (!translation) throw new Error(`Missing ${language} illustration translation: ${source}`);
    return translation;
  }
  const rating = /^(Best|Good|Poor) = ([\d.]+)$/.exec(source);
  if (rating) return `${translateText(language, rating[1])} = ${rating[2]}`;
  const total = /^(.*) out of 10$/.exec(source);
  if (total) return translateIllustration(language, "{0} out of 10").replace("{0}", total[1]);
  const timeframe = /^(Supply|Demand) \(HTF\)$/.exec(source);
  if (timeframe) return `${translateText(language, timeframe[1])} (HTF)`;
  const zone = /^(DZ|SZ) LTF$/.exec(source);
  if (zone) return `${translateIllustration(language, zone[1])} LTF`;
  return translateText(language, source);
}
